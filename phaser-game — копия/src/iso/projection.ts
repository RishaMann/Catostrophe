// §3 промпта. Изометрическая проекция мир → экран — зафиксирована навсегда,
// копируется буквально, не переписывается «по смыслу».
//
// Мировые координаты: wx вправо-вглубь, wy влево-вглубь, wz вверх.
// Единица — 1/32 клетки. Обе функции принимают координаты ОТНОСИТЕЛЬНО
// origin комнаты (дальний угол пола). Смещение origin на экране хранит
// камера (см. room/RoomScene.ts), а не этот модуль.

// мир → экран
export const projX = (wx: number, wy: number) => (wx - wy) / 2;
export const projY = (wx: number, wy: number, wz = 0) => (wx + wy) / 4 - wz / 2;

// экран → плоскость пола (wz = 0)
export const unproject = (sx: number, sy: number) => ({
  wx: sx + 2 * sy,
  wy: 2 * sy - sx,
});
